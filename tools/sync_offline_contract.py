"""Generate or verify version constants. baseline.json is the single source of truth."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_files(b):
    upstream, api, tool = b['upstream'], b['interfaces'], b['toolchain']
    constants = {
        'ProductVersion': b['productVersion'], 'UpstreamVersion': upstream['version'],
        'UpstreamCommit': upstream['commit'], 'ReShadeApi': upstream['apiVersion'],
        'NativeRpc': api['nativeRpc'], 'AutomationBroker': api['automationBroker'],
        'OfflineApi': api['offlineApi'], 'PreviewBridge': api['previewBridge'],
    }
    header = '// Generated by tools/sync_offline_contract.py; edit maintenance/baseline.json.\n#pragma once\n\nnamespace offline_contract\n{\n'
    cs = '// Generated by tools/sync_offline_contract.py; edit maintenance/baseline.json.\nnamespace OfflineReShade.Core;\n\npublic static class BuildContract\n{\n'
    for name, value in constants.items():
        literal = json.dumps(value)
        header += f'\tinline constexpr {"const char *" if isinstance(value, str) else "unsigned int "}{name} = {literal};\n'
        cs += f'    public const {"string" if isinstance(value, str) else "int"} {name} = {literal};\n'
    props = f'''<!-- Generated by tools/sync_offline_contract.py; edit maintenance/baseline.json. -->
<Project>
  <PropertyGroup>
    <Version>{b['productVersion']}</Version>
    <RestorePackagesWithLockFile>true</RestorePackagesWithLockFile>
    <RestoreLockedMode Condition="'$(RestoreLockedMode)' == ''">true</RestoreLockedMode>
    <Deterministic>true</Deterministic>
  </PropertyGroup>
  <!-- Limit the runtime pin to .NET; a global RuntimeFrameworkVersion also overrides the Windows SDK reference pack. -->
  <Target Name="PinOfflineRuntime" BeforeTargets="ProcessFrameworkReferences">
    <ItemGroup>
      <FrameworkReference Update="Microsoft.NETCore.App" RuntimeFrameworkVersion="{tool['runtimeFramework']}" />
    </ItemGroup>
  </Target>
</Project>
'''
    return {'include/offline_contract.hpp': header + '}\n',
            'OfflineReShade.Core/BuildContract.cs': cs + '}\n',
            'maintenance/OfflineVersion.props': props,
            'global.json': json.dumps({'sdk': {'version': tool['dotnetSdk'], 'rollForward': 'disable', 'allowPrerelease': False}}, indent=2) + '\n'}


def sync(root=ROOT, write=False):
    b = json.loads((root / 'maintenance/baseline.json').read_text(encoding='utf-8'))
    for name, content in generated_files(b).items():
        path = root / name
        if write:
            path.write_text(content, encoding='utf-8', newline='\n')
        elif not path.exists() or path.read_text(encoding='utf-8') != content:
            raise ValueError(f'{name} differs from baseline; run python tools/sync_offline_contract.py --write and review the diff.')
    return b


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    sync(write=parser.parse_args().write)
    print('PASS: generated version contract')
